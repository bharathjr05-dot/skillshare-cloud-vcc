package util;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

public class DBUtil {
    private static final String URL = "jdbc:h2:mem:skillshare;DB_CLOSE_DELAY=-1;DATABASE_TO_UPPER=false";
    private static final String USER = "sa";
    private static final String PASS = "";

    static {
        try {
            Class.forName("org.h2.Driver");
            initializeDatabase();
        } catch (ClassNotFoundException e) {
            e.printStackTrace();
        } catch (SQLException e) {
            throw new ExceptionInInitializerError(e);
        }
    }

    public static Connection getConnection() throws SQLException {
        return DriverManager.getConnection(URL, USER, PASS);
    }

    private static void initializeDatabase() throws SQLException {
        try (Connection connection = DriverManager.getConnection(URL, USER, PASS);
             Statement statement = connection.createStatement()) {
            statement.execute("CREATE TABLE IF NOT EXISTS users (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username VARCHAR(50) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL, full_name VARCHAR(100), email VARCHAR(100), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
            statement.execute("CREATE TABLE IF NOT EXISTS skills (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INT NOT NULL, title VARCHAR(150) NOT NULL, description CLOB, location VARCHAR(100), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, CONSTRAINT fk_skills_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE)");
            statement.execute("CREATE TABLE IF NOT EXISTS requests (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, skill_id INT NOT NULL, from_user_id INT NOT NULL, to_user_id INT NOT NULL, message VARCHAR(300), status VARCHAR(10) DEFAULT 'PENDING' CHECK(status IN ('PENDING','ACCEPTED','REJECTED')), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, CONSTRAINT fk_requests_skill FOREIGN KEY(skill_id) REFERENCES skills(id) ON DELETE CASCADE, CONSTRAINT fk_requests_from FOREIGN KEY(from_user_id) REFERENCES users(id) ON DELETE CASCADE, CONSTRAINT fk_requests_to FOREIGN KEY(to_user_id) REFERENCES users(id) ON DELETE CASCADE)");
        }
    }
}
