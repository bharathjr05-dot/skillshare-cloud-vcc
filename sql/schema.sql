-- H2 schema used by the Render Docker deployment.
CREATE TABLE IF NOT EXISTS users (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  full_name VARCHAR(100),
  email VARCHAR(100),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS skills (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INT NOT NULL,
  title VARCHAR(150) NOT NULL,
  description CLOB,
  location VARCHAR(100),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_skills_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS requests (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  skill_id INT NOT NULL,
  from_user_id INT NOT NULL,
  to_user_id INT NOT NULL,
  message VARCHAR(300),
  status VARCHAR(10) DEFAULT 'PENDING' CHECK(status IN ('PENDING','ACCEPTED','REJECTED')),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_requests_skill FOREIGN KEY(skill_id) REFERENCES skills(id) ON DELETE CASCADE,
  CONSTRAINT fk_requests_from FOREIGN KEY(from_user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_requests_to FOREIGN KEY(to_user_id) REFERENCES users(id) ON DELETE CASCADE
);
